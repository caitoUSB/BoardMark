#pragma once

// 开机自启动。
//
// 为什么用注册表而不是"启动"文件夹
// --------------------------------
// Windows 上常见三种做法：
//   1. HKEY_CURRENT_USER\...\CurrentVersion\Run 注册表值   ← 用这个
//   2. 往 %APPDATA%\...\Startup 丢一个 .lnk 快捷方式
//   3. 计划任务
//
// 选 1 的理由：免管理员（只写 HKCU）、按用户隔离、随时可查可撤、
// **任务管理器的「启动」页里能看到并让老师自己关掉** —— 第 3 条很重要：
// 老师不想要的时候不该只能靠卸载软件来摆脱它。
// 做法 2 要建 .lnk（得用 COM 的 IShellLink），代码多得多，收益一样。
//
// 刻意**不存进 settings.json**
// ---------------------------
// 注册表才是唯一事实来源。如果 settings.json 里再存一份，就会出现
// "老师在任务管理器里关掉了，但配置里还写着开" 的分歧，
// 然后界面要么撒谎、要么在下次启动时把老师的选择覆盖回去（那很像流氓软件）。
// 所以：界面打开时**读注册表**显示真实状态，老师拨开关时才写。
//
// 路径会跟着 exe 走
// -----------------
// 老师把整个文件夹挪个地方之后，注册表里记的还是旧路径。
// 所以启动时如果发现已经开着、但记的路径不是当前 exe，就顺手改过来。
// **只有在"已经开着"时才改** —— 关着就绝不去打开它。

#include <QString>

namespace cm {

/// 注册表里的值名，也是任务管理器「启动」页里显示的名字
extern const char *kAutoStartName;

/// 当前是否已设置开机自启动（读注册表，不缓存）
bool isAutoStartEnabled();

/// 打开/关闭开机自启动。写入的是**当前 exe 的完整路径**。
/// 返回是否成功（注册表被策略锁住时会失败）。
bool setAutoStartEnabled(bool on);

/// 注册表里记的命令行。没开启时返回空串。给 --info 排查用。
QString autoStartCommand();

/// 注册表项的位置（给界面提示和 --info 用）
QString autoStartRegistryPath();

/// 启动时调一次：**已经开着的话**，把旧的 exe 路径刷新成当前的。
/// 已经关着就什么都不做（不去打开它）。
/// 返回是否真的改了。
bool refreshAutoStartPath();

// ------------------------------------------------------------------ 改名迁移
//
// 项目原名 ClassMind，2026-10-08 改名为 BoardMark。注册表值名也跟着变了，
// 于是旧的那条会变成指向一个已不存在的 exe 的**死项**，一直挂在任务管理器
// 的「启动」页里。下面两个函数负责把这段过渡处理干净。

/// 改名前用的名字（注册表值名、单实例互斥体名都从它派生）
extern const char *kLegacyName;

/// migrateLegacyAutoStart() 干了什么。调用方据此决定要不要提示老师。
enum class LegacyAutoStartResult {
    Nothing,    ///< 没有旧项，什么都不用做（绝大多数机器）
    Migrated,   ///< 旧项**迁移**成了新项 —— 老师的开机自启被保住了，得说一声
    Removed,    ///< 新项本来就开着，旧项只是冗余，删掉
    Failed,     ///< 注册表读写失败（被组策略 / 安全软件拦住）
};

/// 处理改名留下的旧启动项：**优先迁移，而不是只删。**
///
/// 为什么不能只删（这是改名版早期实现里的真实缺陷）
/// ----------------------------------------------
/// 开机自启动的状态**只存在注册表里**（见本文件开头"刻意不存进
/// settings.json"）。改名之后：
///
///   * 旧名字（ClassMind）那条 —— 是「**这位老师想要开机自启**」的正面证据
///   * 新名字（BoardMark）那条 —— 从来没被写过，
///     **"不存在"不能解释成"老师关掉了"**
///
/// 只删不建的后果：老师升级后开机自启被**静默关掉**。他以为程序还会跟着
/// 开机跑，实际上一整节课都没录到 —— 静默的数据丢失，等发现时课已经上完了。
///
/// 所以规则是：
///   旧项在、新项不在  -> 照**当前 exe** 建一条新项（迁移），再删旧项
///   旧项在、新项也在  -> 旧项是冗余，直接删
///   旧项不在          -> 什么都不做
///
/// **只动自己这两条值，不碰别人写的任何启动项。**
///
/// 调用时机：要在 refreshAutoStartPath() **之前** —— 迁移会把"没有新项"
/// 变成"有新项"，之后 refresh 才有机会纠正可能过期的路径。
LegacyAutoStartResult migrateLegacyAutoStart();

/// 旧版本（ClassMind）现在是不是还在跑？
///
/// 改名后互斥体名也变了，**新旧两版会互不识别** —— 如果旧版还挂在开机自启里，
/// 两个程序可能同时录屏、存出两份重复的会话。所以启动时要查一下并提示。
bool legacyInstanceRunning();

} // namespace cm
