#pragma once

// 白板的识别与**本机自动标定**。
//
// 为什么需要这个
// --------------
// 原来 target_process 是手工填的一个进程名，而且裁切比例（crop_*_percent）
// 是**针对希沃白板在开发机上标定**的一组固定值。这有两个问题：
//
//   1. 不同老师用不同白板软件（希沃白板 / 希沃轻白板 / 鸿合 …），
//      进程名各不相同，不该让老师自己去查。
//   2. **裁切比例跟设备有关，不能随程序发布。**
//      裁切是"画面高度的百分比"，而工具栏的物理高度 =
//      「逻辑高度 × Windows 缩放比」，画面高度 = 屏幕物理分辨率。
//      同一款软件实测：
//          1920x1080 @100%  -> 工具栏约占 6.1%
//          1920x1080 @125%  -> 约占 7.6%
//          3840x2160 @150%  -> 约占 4.6%
//      所以任何写死的百分比在别的机器上都是错的，**只能本机测**。
//
// 于是分成两件事：
//   * WhiteboardBrand     —— 内置表，只记**跨设备通用**的标识（进程名、显示名）。
//                            进程名几乎所有电脑都一样，可以安全内置。
//   * BoardCalibration    —— 本机标定出来的裁切值，**按进程名分开存**
//                            （同一台教室电脑可能装了两套白板，各测各的）。
//                            结构定义在 app/settings.h。
//
// 识别不出来也不影响使用：老师在设置里手动选一次进程，**标定照样会自动进行**。

#include <QString>
#include <QStringList>
#include <vector>

#include "app/settings.h"
#include "capture/window_detector.h"

namespace cm {

/// 一款已知的白板软件。**只含跨设备通用的标识，不含任何采集参数。**
struct WhiteboardBrand {
    QString processName;        ///< 例如 "EasiNote5C.exe"
    QString displayName;        ///< 给人看的名字，例如 "希沃轻白板"
    /// 窗口标题里出现这些词就认为是这款（进程名对不上时的备用线索）
    QStringList titleHints;
};

/// 内置的已知白板列表。
///
/// **这张表只用来"认出是哪一款"，认不出也不会少任何功能** ——
/// 裁切参数一律本机标定，不在这里写死。所以这张表可以放心地慢慢补，
/// 不必等某款软件的参数被标定过才敢加进来。
const std::vector<WhiteboardBrand> &knownWhiteboards();

/// 进程名 -> 显示名。不认识返回空串。
QString brandDisplayName(const QString &processName);

// ------------------------------------------------------------------ 自动识别

struct WhiteboardDetection {
    QString processName;
    QString displayName;
    bool recognized = false;    ///< 是否命中了内置表
    /// **这个白板窗口是不是当前前台窗口** —— 也就是"老师正在用的那个"。
    ///
    /// 这一位是"换课换白板"能自动跟上的关键：旧白板往往根本没关，
    /// 所以"哪个进程有窗口"区分不出老师现在用哪个，"哪个在前台"才行。
    bool foreground = false;
    QString reason;             ///< 判定的依据，写进日志，方便排查选错的情况

    bool ok() const { return recognized && !processName.isEmpty(); }
};

/// 在没有手工指定进程时，从当前窗口里认出白板软件。
///
/// 打分规则（进程名是最硬的证据，权重最高）：
///     进程名相同        +3
///     标题含品牌关键词  +2
/// 品牌证据（上面两项之和）**必须 >= 2 才算候选**，证据不足就不认 ——
/// 不要"猜一个最大的窗口"，选错目标会一直记录错误的窗口，界面上还看不出来。
///
/// 在候选之间排序时，**处于前台的优先**：
///     排名 = 品牌证据 + （在前台 ? 10 : 0）
/// 这样"后台开着白板5、前台在用轻白板"时能正确地选轻白板。
WhiteboardDetection detectWhiteboard(const std::vector<WindowInfo> &windows);

// ------------------------------------------------------------------ 自动标定

/// 自动标定「分析区域裁切」—— 测出白板软件自己的固定工具栏占了多高。
///
/// 判据
/// ----
/// **固定 UI 的横向边缘在每一帧都出现在同一个位置，板书内容的边缘会移动。**
/// 所以对每一行取"跨帧最弱的边缘强度"：
///
///     D[y] = min over frames | 行均值[y] - 行均值[y-1] |
///
/// 工具栏的上下沿在每一帧都很强 -> D 大；
/// 内容边缘只在部分帧强（写字、拖动都会让它换位置）-> 被压到很小。
///
/// 实测（真实素材，希沃白板 34 帧）：
///     工具栏上沿 y=1000 -> 跨帧最弱边缘 62.63（最强 70.40）
///     下一档可疑位置     -> 只有 16.19
/// 差了一个量级，说明这个判据确实能把"每帧都一样的固定 UI"挑出来。
///
/// 为什么要求"有内容变化"
/// ----------------------
/// 如果老师一直不动笔，整幅画面每一帧都一样，**内容的边缘也会变得"每一帧都在
/// 同一位置"**，那就没法把它和工具栏分开。所以必须等到画面真的动过几次，
/// 标定结果才可信。见 kMinChanges。
///
/// 只标上下，不标左右
/// ------------------
/// 左右**故意不自动标定**，保持 0（需要的话老师在设置里手填）。理由：
///   * 现有两款素材（希沃白板 / 希沃轻白板）都没有侧边工具栏，实测都是 0
///   * 列方向的边缘信号被污染得厉害：图像左右边界本身就有巨大导数；
///     而内容如果只是上下拖动、不怎么左右移动，它自己的竖直边缘就不会换位置，
///     跨帧取 min 压不掉，会被误判成侧边工具栏。
///     实测希沃那 34 帧的列方向最强"一致边缘"只有 10.74，
///     而行方向的工具栏边缘是 62.63 —— 差 6 倍，明显不是一类东西。
///   * 裁错 14% 会静默丢掉 28% 的画面宽度，而我没有素材能验证侧边栏该裁多少。
/// 宁可留着不裁（多存几张，事后手动删），也不要靠猜。
class BoardCalibrator {
public:
    /// 至少累计这么多帧才出结果
    static const int kMinFrames = 30;
    /// 期间至少要检测到这么多次内容变化 —— 见上面"为什么要求有内容变化"
    static const int kMinChanges = 5;

    /// 喂一帧的**未裁切**行均值（降采样之后）。
    /// srcH 是原始画面的物理高度，用来把行号换算成百分比。
    void feed(const std::vector<float> &rows, int srcH);

    /// 累计帧数够了、而且画面确实动过 —— 此时 result() 才可信
    bool ready() const
    {
        return m_frames >= kMinFrames && m_changes >= kMinChanges;
    }

    /// 取标定结果。**百分比一律向上取整**：
    /// 多裁一点只是暂时少看一点板面，少裁一点却会让固定 UI 污染相似度判定
    /// （实测完全不裁切时，34 帧真实素材只会存下 1 张）。
    BoardCalibration result() const;

    int frames() const { return m_frames; }
    int changes() const { return m_changes; }
    bool empty() const { return m_frames == 0; }
    void reset();

private:
    /// 每帧更新一次的"跨帧最弱边缘"
    std::vector<float> m_minRowEdge;
    std::vector<float> m_prevRows;
    int m_rows = 0;
    int m_srcH = 0;
    int m_frames = 0;
    int m_changes = 0;
};

} // namespace cm
